USE ROLE AGENT_AUTHZ_ADMIN;
CREATE WAREHOUSE IF NOT EXISTS AGENT_AUTHZ_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 INITIALLY_SUSPENDED = TRUE;
CREATE SCHEMA IF NOT EXISTS AGENT_AUTHZ_DEMO.BANKING;
USE SCHEMA AGENT_AUTHZ_DEMO.BANKING;

-- ---------------------------------------------------------------------
-- Synthetic data
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS CUSTOMERS AS
SELECT
  'C' || LPAD(SEQ4()::STRING, 5, '0')                                          AS CUSTOMER_ID,
  ARRAY_CONSTRUCT('Olivia','Liam','Aoife','Noah','Saoirse','Daan','Emma','Jack','Fenna','Oscar')[UNIFORM(0,9,RANDOM())]::STRING
    || ' ' || ARRAY_CONSTRUCT('Smith','Murphy','de Vries','Jones','Kelly','Bakker','Taylor','Walsh')[UNIFORM(0,7,RANDOM())]::STRING AS FULL_NAME,
  LOWER('cust' || SEQ4() || '@example.com')                                    AS EMAIL,
  DATEADD(day, -UNIFORM(6570, 29200, RANDOM()), CURRENT_DATE())                AS DATE_OF_BIRTH,
  'GB' || UNIFORM(10,99,RANDOM()) || 'DEMO' || LPAD(UNIFORM(0,99999999,RANDOM())::STRING, 14, '0') AS IBAN,
  ARRAY_CONSTRUCT('RETAIL','PREMIER','PRIVATE','BUSINESS')[UNIFORM(0,3,RANDOM())]::STRING AS SEGMENT,
  ARRAY_CONSTRUCT('UK','UK','UK','IE','NL')[UNIFORM(0,4,RANDOM())]::STRING      AS REGION,
  UNIFORM(1, 100, RANDOM())                                                    AS RISK_SCORE
FROM TABLE(GENERATOR(ROWCOUNT => 500));

CREATE TABLE IF NOT EXISTS TRANSACTIONS AS
SELECT
  'T' || LPAD(SEQ4()::STRING, 7, '0')                                          AS TXN_ID,
  c.CUSTOMER_ID,
  ROUND(UNIFORM(1, 500000, RANDOM()) / 100, 2)                                 AS AMOUNT,
  IFF(c.REGION = 'UK', 'GBP', 'EUR')                                           AS CURRENCY,
  ARRAY_CONSTRUCT('Tesco','Ryanair','Albert Heijn','Amazon','Shell','Deliveroo')[UNIFORM(0,5,RANDOM())]::STRING AS MERCHANT,
  DATEADD(minute, -UNIFORM(0, 525600, RANDOM()), CURRENT_TIMESTAMP())          AS TXN_TS,
  c.REGION,
  UNIFORM(0, 50, RANDOM()) = 0                                                 AS FRAUD_FLAG
FROM CUSTOMERS c, TABLE(GENERATOR(ROWCOUNT => 10));

-- ---------------------------------------------------------------------
-- Horizon classification (data owners classify once, here).
-- ---------------------------------------------------------------------
USE SCHEMA AGENT_AUTHZ_DEMO.GOVERNANCE;
CREATE TAG IF NOT EXISTS DATA_SENSITIVITY ALLOWED_VALUES 'PUBLIC','INTERNAL','CONFIDENTIAL','RESTRICTED'
  PROPAGATE = ON_DEPENDENCY_AND_DATA_MOVEMENT
  COMMENT = 'Sensitivity level, harvested by the PDP as resource.sensitivity (0-3)';
CREATE TAG IF NOT EXISTS ALLOWED_PURPOSES
  COMMENT = 'Comma separated processing purposes (GDPR purpose limitation)';
CREATE TAG IF NOT EXISTS ROW_SCOPE_COLUMN
  COMMENT = 'Table tag: column whose values form PDP RowScope resources';
CREATE TAG IF NOT EXISTS PDP_RESOURCE_ID
  COMMENT = 'Column tag: the Cedar Column id. Joins Snowflake columns to PDP decisions';

-- ---------------------------------------------------------------------
-- PDP state in Snowflake (written ONLY by the PDP / sync identity)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS PDP_SYNC_STATE (
  ID INT, LAST_HEARTBEAT TIMESTAMP_LTZ, POLICY_HASH STRING, MAX_STALENESS_MINUTES INT);
INSERT INTO PDP_SYNC_STATE SELECT 1, '1970-01-01'::TIMESTAMP_LTZ, 'none', 2
  WHERE NOT EXISTS (SELECT 1 FROM PDP_SYNC_STATE);
CREATE TABLE IF NOT EXISTS PDP_DECISIONS (
  DECISION_ID STRING, BATCH_ID STRING, TS TIMESTAMP_TZ, AGENT STRING, AGENT_APP_ID STRING,
  AGENT_MODE STRING, RISK_TIER STRING, ON_BEHALF_OF STRING, ACTION STRING,
  RESOURCE_TYPE STRING, RESOURCE_ID STRING, PURPOSE STRING, HUMAN_APPROVAL BOOLEAN,
  DECISION BOOLEAN, DETERMINING_POLICIES ARRAY, POLICY_HASH STRING, RAW VARIANT);

