USE SCHEMA AGENT_AUTHZ_DEMO.BANKING;
ALTER TABLE CUSTOMERS SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.ROW_SCOPE_COLUMN = 'REGION';
