-- =====================================================================
-- Snowflake side of the demo.  Run by snowflake/deploy.py which replaces
-- the ${...} placeholders from .env.  Requires ACCOUNTADMIN (once).
--
-- Snowflake plays two roles:
--   1. Enforcement point of last resort: even if an agent bypasses the
--      gateway, Horizon policies enforce the PDP-compiled ceiling.
--   2. Source of data classification for the PDP (Horizon tags).
-- =====================================================================

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS AGENT_AUTHZ_ADMIN;          -- owns governance objects
CREATE ROLE IF NOT EXISTS AGENT_AUTHZ_SYNC;           -- the PDP <-> Snowflake sync job
CREATE ROLE IF NOT EXISTS AGENT_ADVISOR_COPILOT;      -- delegated agent (OBO)
CREATE ROLE IF NOT EXISTS AGENT_FRAUD_SENTINEL;       -- autonomous agent
CREATE ROLE IF NOT EXISTS AGENT_MARKETING_GENIE;      -- autonomous agent, not approved
GRANT ROLE AGENT_AUTHZ_ADMIN TO ROLE SYSADMIN;
GRANT ROLE AGENT_AUTHZ_SYNC  TO ROLE AGENT_AUTHZ_ADMIN;
GRANT CREATE DATABASE, CREATE WAREHOUSE ON ACCOUNT TO ROLE AGENT_AUTHZ_ADMIN;
GRANT APPLY MASKING POLICY, APPLY ROW ACCESS POLICY, APPLY TAG ON ACCOUNT TO ROLE AGENT_AUTHZ_ADMIN;
GRANT DATABASE ROLE SNOWFLAKE.GOVERNANCE_VIEWER TO ROLE AGENT_AUTHZ_ADMIN;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE TO ROLE AGENT_AUTHZ_ADMIN;
GRANT ROLE AGENT_AUTHZ_ADMIN TO USER "${ADMIN_USER}";

-- Autonomous agents get their own Snowflake identity (SERVICE_AGENT).
CREATE USER IF NOT EXISTS FRAUD_SENTINEL_AGENT
  TYPE = SERVICE_AGENT
  LOGIN_NAME = '${SENTINEL_SP_OID}'
  DEFAULT_ROLE = AGENT_FRAUD_SENTINEL
  COMMENT = 'Entra workload identity of the fraud-sentinel agent';
CREATE USER IF NOT EXISTS MARKETING_GENIE_AGENT
  TYPE = SERVICE_AGENT
  LOGIN_NAME = '${GENIE_SP_OID}'
  DEFAULT_ROLE = AGENT_MARKETING_GENIE
  COMMENT = 'Entra workload identity of the marketing-genie agent';
GRANT ROLE AGENT_FRAUD_SENTINEL  TO USER FRAUD_SENTINEL_AGENT;
GRANT ROLE AGENT_MARKETING_GENIE TO USER MARKETING_GENIE_AGENT;
-- The delegated agent role is granted to the humans who may use the copilot.
GRANT ROLE AGENT_ADVISOR_COPILOT TO USER "${DEMO_SNOWFLAKE_USER}";

-- Sync job identity (key-pair, not agentic: it is plumbing, not an agent).
CREATE USER IF NOT EXISTS AGENT_AUTHZ_SYNC_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = AGENT_AUTHZ_SYNC
  RSA_PUBLIC_KEY = '${SYNC_PUBLIC_KEY}'
  COMMENT = 'PDP <-> Snowflake entitlement and classification sync';
ALTER USER AGENT_AUTHZ_SYNC_SVC SET RSA_PUBLIC_KEY = '${SYNC_PUBLIC_KEY}';
GRANT ROLE AGENT_AUTHZ_SYNC TO USER AGENT_AUTHZ_SYNC_SVC;

-- Privilege ceiling for every agent session (Restricted Session Scope):
-- agents are read-only whatever the PDP says.
CREATE DATABASE IF NOT EXISTS AGENT_AUTHZ_DEMO;
CREATE SCHEMA IF NOT EXISTS AGENT_AUTHZ_DEMO.GOVERNANCE;
CREATE SESSION POLICY IF NOT EXISTS AGENT_AUTHZ_DEMO.GOVERNANCE.AGENT_READONLY
  AGENT_RESTRICTED_SESSION_SCOPE = 'SNOWFLAKE$DATA_READ'
  COMMENT = 'Agents may only read, never write or change objects';
EXECUTE IMMEDIATE $$
BEGIN
  ALTER USER FRAUD_SENTINEL_AGENT  SET SESSION POLICY AGENT_AUTHZ_DEMO.GOVERNANCE.AGENT_READONLY;
  ALTER USER MARKETING_GENIE_AGENT SET SESSION POLICY AGENT_AUTHZ_DEMO.GOVERNANCE.AGENT_READONLY;
EXCEPTION WHEN OTHER THEN NULL;   -- already attached on re-deploy
END;
$$;
-- For delegated agents the same ceiling can be set account-wide
-- (ALTER ACCOUNT SET SESSION POLICY ...): it only applies while an agent is
-- active, so the humans' own sessions keep their normal privileges.

GRANT OWNERSHIP ON DATABASE AGENT_AUTHZ_DEMO TO ROLE AGENT_AUTHZ_ADMIN COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA AGENT_AUTHZ_DEMO.GOVERNANCE TO ROLE AGENT_AUTHZ_ADMIN COPY CURRENT GRANTS;

