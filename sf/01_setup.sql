  COLUMN FULL_NAME     SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'RESTRICTED',
                                AGENT_AUTHZ_DEMO.GOVERNANCE.ALLOWED_PURPOSES = 'customer_service,kyc_review',
  COLUMN EMAIL         SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'CONFIDENTIAL',
                                AGENT_AUTHZ_DEMO.GOVERNANCE.ALLOWED_PURPOSES = 'customer_service',
  COLUMN DATE_OF_BIRTH SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'RESTRICTED',
                                AGENT_AUTHZ_DEMO.GOVERNANCE.ALLOWED_PURPOSES = 'kyc_review',
  COLUMN IBAN          SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'RESTRICTED',
                                AGENT_AUTHZ_DEMO.GOVERNANCE.ALLOWED_PURPOSES = 'kyc_review,fraud_detection',
  COLUMN SEGMENT       SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'INTERNAL',
  COLUMN REGION        SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'INTERNAL',
  COLUMN RISK_SCORE    SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'CONFIDENTIAL';
ALTER TABLE TRANSACTIONS MODIFY
  COLUMN TXN_ID      SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'INTERNAL',
  COLUMN CUSTOMER_ID SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'INTERNAL',
  COLUMN AMOUNT      SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'CONFIDENTIAL',
  COLUMN CURRENCY    SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'PUBLIC',
  COLUMN MERCHANT    SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'INTERNAL',
  COLUMN TXN_TS      SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'INTERNAL',
  COLUMN REGION      SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'INTERNAL',
  COLUMN FRAUD_FLAG  SET TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY = 'CONFIDENTIAL';

