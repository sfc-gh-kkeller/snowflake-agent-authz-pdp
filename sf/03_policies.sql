-- =====================================================================
-- Enforcement of PDP decisions INSIDE Snowflake (Horizon policies).
--
-- The PDP writes every PERMIT as a short-lived "decision grant" bound to
-- the agent's Snowflake session (DECISION_GRANTS). A HYBRID TABLE is the
-- better fit (row-level point writes/locks); this demo account uses
-- Tri-Secret Secure without dedicated storage, so it uses a standard table. Masking and row access policies only reveal
-- data the PDP has just permitted for THIS session, user and role.
--
--   gateway bypassed (agent connects directly)  -> no grants -> nothing
--   gateway asks for A but queries A+B          -> B masked
--   PDP down                                    -> no new grants, old
--                                                  ones expire (TTL) and
--                                                  the heartbeat goes stale
--   human (non-agent) session                   -> normal RBAC, untouched
-- =====================================================================
USE ROLE AGENT_AUTHZ_ADMIN;
USE SCHEMA AGENT_AUTHZ_DEMO.GOVERNANCE;

-- detach previous versions (idempotent re-deploy)
ALTER TAG IF EXISTS PDP_RESOURCE_ID UNSET
  MASKING POLICY PDP_MASK_STRING, MASKING POLICY PDP_MASK_NUMBER, MASKING POLICY PDP_MASK_DATE,
  MASKING POLICY PDP_MASK_BOOLEAN, MASKING POLICY PDP_MASK_TS;
ALTER TABLE AGENT_AUTHZ_DEMO.BANKING.CUSTOMERS    DROP ALL ROW ACCESS POLICIES;
ALTER TABLE AGENT_AUTHZ_DEMO.BANKING.TRANSACTIONS DROP ALL ROW ACCESS POLICIES;

CREATE TABLE IF NOT EXISTS DECISION_GRANTS (   -- or: CREATE HYBRID TABLE
  GRANT_ID        STRING,
  DECISION_ID     STRING NOT NULL,          -- joins to the PDP decision log
  SESSION_ID      NUMBER NOT NULL,          -- CURRENT_SESSION() of the agent
  SNOWFLAKE_LOGIN STRING NOT NULL,          -- token subject: upn or SP object id
  SNOWFLAKE_ROLE  STRING NOT NULL,
  KIND            STRING NOT NULL,          -- COLUMN | ROWS
  RESOURCE_ID     STRING NOT NULL,          -- CUSTOMERS.EMAIL | CUSTOMERS/UK
  EXPIRES_AT      TIMESTAMP_LTZ NOT NULL
);
GRANT SELECT, INSERT, DELETE ON TABLE DECISION_GRANTS TO ROLE AGENT_AUTHZ_SYNC;

-- login_name -> user name (CURRENT_USER() returns the name), kept by the
-- Horizon sync, so grants bind to the exact identity in the Entra token.
CREATE TABLE IF NOT EXISTS USER_DIRECTORY (LOGIN_NAME STRING, USER_NAME STRING);

-- Fail closed: TRUE only while the PDP heartbeat is fresh.
CREATE OR REPLACE FUNCTION PDP_IS_FRESH()
RETURNS BOOLEAN
AS $$
  SELECT COALESCE(MAX(LAST_HEARTBEAT > DATEADD(minute, -MAX_STALENESS_MINUTES, CURRENT_TIMESTAMP())), FALSE)
  FROM AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_SYNC_STATE
$$;

-- Single place that answers "did the PDP permit this, for this session?"
CREATE OR REPLACE FUNCTION PDP_PERMITS(kind STRING, resource_id STRING)
RETURNS BOOLEAN
AS $$
  NOT COALESCE(SYS_CONTEXT('SNOWFLAKE$CURRENT', 'IS_AGENT_ACTIVATED')::BOOLEAN, FALSE)
  OR (
    AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_IS_FRESH()
    AND EXISTS (
      SELECT 1 FROM AGENT_AUTHZ_DEMO.GOVERNANCE.DECISION_GRANTS g
      WHERE g.SESSION_ID     = CURRENT_SESSION()::NUMBER
        AND g.SNOWFLAKE_LOGIN IN (SELECT d.LOGIN_NAME FROM AGENT_AUTHZ_DEMO.GOVERNANCE.USER_DIRECTORY d
                                  WHERE d.USER_NAME = CURRENT_USER())
        AND g.SNOWFLAKE_ROLE = CURRENT_ROLE()
        AND g.KIND           = kind
        AND g.RESOURCE_ID    = resource_id
        AND g.EXPIRES_AT     > CURRENT_TIMESTAMP()))
$$;

-- Tag-based masking: every column carrying PDP_RESOURCE_ID is covered.
CREATE OR REPLACE MASKING POLICY PDP_MASK_STRING AS (val STRING) RETURNS STRING ->
  IFF(AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_PERMITS('COLUMN',
        SYSTEM$GET_TAG_ON_CURRENT_COLUMN('AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_RESOURCE_ID')),
      val, '***PDP-DENIED***');
CREATE OR REPLACE MASKING POLICY PDP_MASK_NUMBER AS (val NUMBER(38,2)) RETURNS NUMBER(38,2) ->
  IFF(AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_PERMITS('COLUMN',
        SYSTEM$GET_TAG_ON_CURRENT_COLUMN('AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_RESOURCE_ID')),
      val, NULL);
CREATE OR REPLACE MASKING POLICY PDP_MASK_DATE AS (val DATE) RETURNS DATE ->
  IFF(AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_PERMITS('COLUMN',
        SYSTEM$GET_TAG_ON_CURRENT_COLUMN('AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_RESOURCE_ID')),
      val, NULL);
CREATE OR REPLACE MASKING POLICY PDP_MASK_BOOLEAN AS (val BOOLEAN) RETURNS BOOLEAN ->
  IFF(AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_PERMITS('COLUMN',
        SYSTEM$GET_TAG_ON_CURRENT_COLUMN('AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_RESOURCE_ID')),
      val, NULL);
CREATE OR REPLACE MASKING POLICY PDP_MASK_TS AS (val TIMESTAMP_LTZ) RETURNS TIMESTAMP_LTZ ->
  IFF(AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_PERMITS('COLUMN',
        SYSTEM$GET_TAG_ON_CURRENT_COLUMN('AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_RESOURCE_ID')),
      val, NULL);
ALTER TAG PDP_RESOURCE_ID SET
  MASKING POLICY PDP_MASK_STRING, MASKING POLICY PDP_MASK_NUMBER, MASKING POLICY PDP_MASK_DATE,
  MASKING POLICY PDP_MASK_BOOLEAN, MASKING POLICY PDP_MASK_TS;

-- Row access: the RowScope id is "<TABLE>/<REGION>".
CREATE OR REPLACE ROW ACCESS POLICY PDP_ROWS_CUSTOMERS AS (region STRING) RETURNS BOOLEAN ->
  AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_PERMITS('ROWS', 'CUSTOMERS/' || region);
CREATE OR REPLACE ROW ACCESS POLICY PDP_ROWS_TRANSACTIONS AS (region STRING) RETURNS BOOLEAN ->
  AGENT_AUTHZ_DEMO.GOVERNANCE.PDP_PERMITS('ROWS', 'TRANSACTIONS/' || region);
ALTER TABLE AGENT_AUTHZ_DEMO.BANKING.CUSTOMERS    ADD ROW ACCESS POLICY PDP_ROWS_CUSTOMERS ON (REGION);
ALTER TABLE AGENT_AUTHZ_DEMO.BANKING.TRANSACTIONS ADD ROW ACCESS POLICY PDP_ROWS_TRANSACTIONS ON (REGION);

-- ---------------------------------------------------------------------
-- Data Movement Policy: bulk-export brake for agents on every
-- classified column, independent of the PDP (blast-radius limit).
-- ---------------------------------------------------------------------
EXECUTE IMMEDIATE $$
BEGIN
  ALTER TAG AGENT_AUTHZ_DEMO.GOVERNANCE.DATA_SENSITIVITY
    UNSET DATA MOVEMENT POLICY AGENT_AUTHZ_DEMO.GOVERNANCE.AGENT_GUARDRAILS;
EXCEPTION WHEN OTHER THEN NULL;   -- first deploy: nothing attached yet
END;
$$;
DROP DATA MOVEMENT POLICY IF EXISTS AGENT_GUARDRAILS;
CREATE OR REPLACE DATA MOVEMENT RULE AGENT_MAX_ROWS
  TYPE = 'AGENT_ACCESS'
  MAX_ROWS AS () RETURNS INTEGER -> (200);
CREATE OR REPLACE DATA MOVEMENT RULE NO_EXTERNAL_UNLOAD
  TYPE = 'COPY_INTO_EXTERNAL_STAGE'
  MAX_ROWS AS () RETURNS INTEGER -> (0);
CREATE OR REPLACE DATA MOVEMENT POLICY AGENT_GUARDRAILS
  ENFORCE_RULES = (AGENT_MAX_ROWS, NO_EXTERNAL_UNLOAD);
ALTER TAG DATA_SENSITIVITY SET DATA MOVEMENT POLICY AGENT_GUARDRAILS;
